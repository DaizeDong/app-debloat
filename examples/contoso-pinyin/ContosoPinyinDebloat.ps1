        $v = switch ($kind) { 'DWord' { [int]$value } 'QWord' { [long]$value } 'MultiString' { [string[]]@($value) } default { [string]$value } }
        $k.SetValue($name, $v, $rk)
    } finally { $k.Close(); $b.Close() }
}
