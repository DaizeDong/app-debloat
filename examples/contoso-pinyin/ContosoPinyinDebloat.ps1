function Get-AdActionPlan($a) {
    $items = New-Object System.Collections.Generic.List[object]
    $type = AdGet $a 'type'; $id = AdGet $a 'id'
    switch ($type) {
        'service-disable' {
            foreach ($n in @(AdGet $a 'target' @())) {
                if ($script:Ad.CoreSvcs -contains $n.ToLowerInvariant()) { throw "core-function contract protects service $n" }
                $s = Get-AdService $n
                if (-not $s) { Say 'SKIP' "service $n not present"; continue }
                if ($s.StartMode -eq 'Disabled') { Say 'SKIP' "service $n already disabled"; continue }
                $items.Add((New-AdItem $a 'service' "svc:$n" "Disable service $n (was $($s.StartMode), $($s.State))" @{ name = $n; stop = [bool](AdGet $a 'stop' $true) } `
                    @{ startMode = "$($s.StartMode)"; state = "$($s.State)"; delayed = [bool](AdGet $s 'DelayedAutoStart' $false) } ([ordered]@{ startMode = 'Disabled' })))
            }
        }
        'task-disable' {
            foreach ($t in @(AdGet $a 'target' @())) {
                $i = $t.LastIndexOf('\'); $tp = if ($i -ge 0) { $t.Substring(0, $i + 1) } else { '\' }; $tn = $t.Substring($i + 1)
                $found = @(Get-AdTasks $tp $tn | Where-Object { $_.TaskName -notlike "$($script:Ad.Prefix)Debloat-*" })
                if (-not $found) { Say 'SKIP' "task $t not present"; continue }
                foreach ($f in $found) {
                    if ("$($f.State)" -eq 'Disabled') { Say 'SKIP' "task $($f.TaskPath)$($f.TaskName) already disabled"; continue }
                    $ti = Get-AdTaskIdentity $f
                    $items.Add((New-AdItem $a 'task' "task:$($f.TaskPath)$($f.TaskName)" "Disable scheduled task $($f.TaskPath)$($f.TaskName)" @{ path = $f.TaskPath; name = $f.TaskName } `
                        @{ state = "$($f.State)"; actions = $ti } ([ordered]@{ state = 'Disabled'; actions = $ti })))
                }
            }
        }
        'file-placeholder-dir' {
            $create = [bool](AdGet $a 'createIfMissing' $false); $bk = [bool](AdGet $a 'backup' $true)
            foreach ($f in (Get-AdTargets $a)) {
                Assert-AdPathSafe $f
                if (Test-Path -LiteralPath $f -PathType Container) { Say 'SKIP' "$f is already a placeholder directory"; continue }
                if (Test-Path -LiteralPath $f -PathType Leaf) {
                    $fi = Get-Item -LiteralPath $f -Force
                    $items.Add((New-AdItem $a 'file2dir' "fs:$f" "Replace file with placeholder directory: $f" @{ path = $f; backup = $bk; stopHosts = @(@(AdGet $a 'stopHosts' @()) | ForEach-Object { Expand-AdPath $_ }) } `
                        @{ existed = $true; size = $fi.Length; sha256 = (Get-AdSha256 $f); fileVersion = $fi.VersionInfo.FileVersion; backup = $null } ([ordered]@{ kind = 'emptyDir' })))
                } elseif ($create -and $f -notmatch '[\*\?]') {
                    $items.Add((New-AdItem $a 'file2dir' "fs:$f" "Pre-create placeholder directory (blocks re-download): $f" @{ path = $f; backup = $false; stopHosts = @() } @{ existed = $false } ([ordered]@{ kind = 'emptyDir' })))
                }
            }
        }
        'dir-placeholder-file' {
            $create = [bool](AdGet $a 'createIfMissing' $false); $bk = [bool](AdGet $a 'backup' $true)
            foreach ($d in (Get-AdTargets $a)) {
                Assert-AdPathSafe $d
                if (Test-Path -LiteralPath $d -PathType Leaf) { Say 'SKIP' "$d is already a placeholder file"; continue }
                if (Test-Path -LiteralPath $d -PathType Container) {
                    if (AdGet $a 'checkLoaded' $true) {
                        $dlls = @(Get-ChildItem -LiteralPath $d -Recurse -Filter *.dll -Force -ErrorAction SilentlyContinue | ForEach-Object { $_.Name } | Select-Object -Unique)
                        $state = @($dlls | ForEach-Object { Test-AdModuleLoaded $_ })
                        if ($state -contains $true -or $state -contains $null) { Say 'WARN' "$d has DLLs loaded in a running process (or the check failed); deferred: reboot and run again"; continue }
                    }
                    $files = @(Get-ChildItem -LiteralPath $d -Recurse -File -Force -ErrorAction Stop)
                    $bytes = 0; foreach ($x in $files) { $bytes += $x.Length }
                    $items.Add((New-AdItem $a 'dir2file' "fs:$d" "Replace folder with read-only placeholder file: $d ($($files.Count) files)" @{ path = $d; backup = $bk } `
                        @{ existed = $true; fileCount = $files.Count; bytes = $bytes; backup = $null } ([ordered]@{ kind = 'placeholderFile' })))
                } elseif ($create -and $d -notmatch '[\*\?]') {
                    $items.Add((New-AdItem $a 'dir2file' "fs:$d" "Pre-create read-only placeholder file (blocks re-download): $d" @{ path = $d; backup = $false } @{ existed = $false } ([ordered]@{ kind = 'placeholderFile' })))
                }
            }
        }
        'acl-deny-write' {
            $pr = AdGet $a 'principal' 'CurrentUser'
            $sid = switch ($pr) { 'CurrentUser' { [Security.Principal.WindowsIdentity]::GetCurrent().User.Value } 'Users' { 'S-1-5-32-545' } default { $pr } }
            if ($sid -notmatch '^S-1-[\d-]+$') { throw "principal must be CurrentUser, Users or a SID: $pr" }
