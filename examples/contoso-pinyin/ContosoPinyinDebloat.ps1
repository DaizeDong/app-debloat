$script:AdDenyWriteRights = [int]([Security.AccessControl.FileSystemRights]'WriteData, AppendData, WriteExtendedAttributes, WriteAttributes')
function Get-AdDenyRights([string]$path, [string]$sid, [int]$inheritance) {
    $sec = (Get-Item -LiteralPath $path -Force).GetAccessControl('Access')
    $sum = 0
    foreach ($r in $sec.GetAccessRules($true, $false, [Security.Principal.SecurityIdentifier])) {
        if ("$($r.AccessControlType)" -eq 'Deny' -and $r.IdentityReference.Value -eq $sid -and [int]$r.InheritanceFlags -eq $inheritance -and [int]$r.PropagationFlags -eq 0) {
            $sum = $sum -bor [int]$r.FileSystemRights
        }
    }
    $sum
}
# Adds, or with -Remove takes away, exactly $rights from the explicit deny entry of $sid with these inheritance flags.
# Other entries, and other rights in the same entry, are left as they are.
function Set-AdDenyAce([string]$path, [string]$sid, [int]$rights, [int]$inheritance, [switch]$Remove) {
    $item = Get-Item -LiteralPath $path -Force
    $sec = $item.GetAccessControl('Access')
    $id = New-Object Security.Principal.SecurityIdentifier $sid
    $mk = { param($r) New-Object Security.AccessControl.FileSystemAccessRule($id, [Security.AccessControl.FileSystemRights]$r,
                [Security.AccessControl.InheritanceFlags]$inheritance, [Security.AccessControl.PropagationFlags]::None, [Security.AccessControl.AccessControlType]::Deny) }
    if ($Remove) {
        foreach ($r in @($sec.GetAccessRules($true, $false, [Security.Principal.SecurityIdentifier]))) {
            if ("$($r.AccessControlType)" -ne 'Deny' -or $r.IdentityReference.Value -ne $sid -or [int]$r.InheritanceFlags -ne $inheritance -or [int]$r.PropagationFlags -ne 0) { continue }
            if (-not ([int]$r.FileSystemRights -band $rights)) { continue }
            [void]$sec.RemoveAccessRuleSpecific($r)
            $restRights = [int]$r.FileSystemRights -band (-bnot $rights)
            if ($restRights) { $sec.AddAccessRule((& $mk $restRights)) }
        }
    } else { $sec.AddAccessRule((& $mk $rights)) }
    $item.SetAccessControl($sec)
}

