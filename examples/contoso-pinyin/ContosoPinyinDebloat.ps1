function Find-AdUninstallEntry($rule) {
    $dn = AdGet $rule 'displayName'; $pub = AdGet $rule 'publisher'
    if (-not $dn) { return $null }
    $sub = 'SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall'
    foreach ($spec in @(@('HKLM', 64), @('HKLM', 32), @('HKCU', 64))) {
        $b = Open-AdHive $spec[0] $spec[1]; $root = $b.OpenSubKey($sub)
        if ($root) {
            foreach ($n in $root.GetSubKeyNames()) {
                $k = $root.OpenSubKey($n); if (-not $k) { continue }
                $d = [string]$k.GetValue('DisplayName'); $p = [string]$k.GetValue('Publisher')
                if ($d -match $dn -and (-not $pub -or $p -match $pub)) {
                    $e = @{ DisplayVersion = [string]$k.GetValue('DisplayVersion'); InstallLocation = [string]$k.GetValue('InstallLocation')
                            DisplayIcon = [string]$k.GetValue('DisplayIcon'); UninstallString = [string]$k.GetValue('UninstallString') }
                    $k.Close(); $root.Close(); $b.Close(); return $e
                }
                $k.Close()
            }
            $root.Close()
        }
        $b.Close()
    }
    $null
}
function Get-AdDirFromCommand([string]$cmd) {
    if (-not $cmd) { return $null }
    $c = $cmd.Trim()
    if ($c.StartsWith('"')) { $j = $c.IndexOf('"', 1); if ($j -lt 0) { return $null }; $c = $c.Substring(1, $j - 1) } else { $c = ($c -split ',')[0]; if ($c -match '^(.+?\.exe)') { $c = $Matches[1] } }
    $c = [Environment]::ExpandEnvironmentVariables($c)
    try { [IO.Path]::GetDirectoryName($c) } catch { $null }
}
# Vendor identity of a candidate root: $null when it passes, else the reason. Applies to every source,
# including -InstallRoot and the environment variable, so an override cannot point at a look-alike folder.
function Get-AdRootIdentityRefusal($r, [string]$d) {
    $id = AdGet $r 'identity'
    foreach ($f in @(AdGet $id 'files' @())) { if (-not (Test-Path -LiteralPath (Join-Path $d $f))) { return "expected file $f is missing" } }
    foreach ($t in @(AdGet $id 'text' @())) {
        $f = AdGet $t 'file'; $p = Join-Path $d $f
        if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { return "identity file $f is missing" }
        if ([IO.File]::ReadAllText($p) -notmatch (AdGet $t 'regex')) { return "identity file $f does not match /$(AdGet $t 'regex')/" }
    }
    $sg = AdGet $id 'signer'
    if ($sg) {
        foreach ($f in @(AdGet $sg 'files' @())) {
            $p = Join-Path $d $f
            if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { return "signed file $f is missing" }
            $s = Get-AuthenticodeSignature -LiteralPath $p
            if ("$($s.Status)" -ne 'Valid') { return "$f signature status is $($s.Status)" }
            if ($s.SignerCertificate.Subject -notmatch (AdGet $sg 'subject')) { return "$f is signed by '$($s.SignerCertificate.Subject)', expected /$(AdGet $sg 'subject')/" }
        }
    }
    $null
}
function Resolve-AdInstallRoot($m, [string]$override) {
    $r = AdGet $m 'installRoot'
    $must = @(AdGet $r 'mustContain' @())
    $cands = New-Object System.Collections.Generic.List[object]
    if ($override) { $cands.Add(@('-InstallRoot', $override, $true)) }
    $ev = AdGet $r 'envVar'
    if ($ev -and [Environment]::GetEnvironmentVariable($ev)) { $cands.Add(@("env:$ev", [Environment]::GetEnvironmentVariable($ev), $true)) }
    $u = AdGet $r 'uninstall'
    if ($u) {
        $e = Find-AdUninstallEntry $u; $script:Ad.Uninstall = $e
        if ($e) {
            if ($e.InstallLocation) { $cands.Add(@('Uninstall InstallLocation', $e.InstallLocation, $false)) }
            $d = Get-AdDirFromCommand $e.DisplayIcon; if ($d) { $cands.Add(@('Uninstall DisplayIcon', $d, $false)) }
            $d = Get-AdDirFromCommand $e.UninstallString; if ($d) { $cands.Add(@('Uninstall UninstallString', $d, $false)) }
        }
    }
    $sv = AdGet $r 'service'
    if ($sv) {
        $name = AdGet $sv 'name'
        $s = $null; try { $s = Get-AdService $name } catch { Say 'WARN' "service query for $name failed ($($_.Exception.Message)); not used to find the install root" }
        if ($s) {
            $d = Get-AdDirFromCommand $s.PathName
            for ($i = 0; $i -lt [int](AdGet $sv 'levelsUp' 0) -and $d; $i++) { $d = [IO.Path]::GetDirectoryName($d) }
            if ($d) { $cands.Add(@("service $name", $d, $false)) }
        }
    }
    foreach ($c in @(AdGet $r 'candidates' @())) { $cands.Add(@('candidate', [Environment]::ExpandEnvironmentVariables($c), $false)) }
    foreach ($c in $cands) {
        $d = $c[1].Trim().Trim('"'); $explicit = $c[2]
        $missing = @($must | Where-Object { -not (Test-Path -LiteralPath (Join-Path $d $_)) })
        if (-not (Test-Path -LiteralPath $d -PathType Container) -or $missing) {
            # An explicit override that does not fit is an error, never a silent fall-through to another root.
            if ($explicit) { throw "install root '$d' (from $($c[0])) is not $(AdGet $m 'name'): missing $(if ($missing) { $missing -join ', ' } else { 'the folder' })" }
            continue
        }
        $why = Get-AdRootIdentityRefusal $r $d
        if ($why) {
            if ($explicit) { throw "install root '$d' (from $($c[0])) fails the vendor identity check: $why" }
            Say 'WARN' "candidate root $d (from $($c[0])) fails the vendor identity check: $why"; continue
        }
        return @((Get-AdNormal $d), $c[0])
    }
    throw "$(AdGet $m 'name') is not installed (no candidate root contains $($must -join ', ') and passes the identity check)."
}
function Resolve-AdVersionDir($m, [string]$root) {
    $vd = AdGet $m 'versionDir'
    if (-not $vd) { return $root }
    $must = AdGet $vd 'mustContain' ''
    $reg = AdGet $vd 'registry'
    if ($reg) {
        $hp = Split-AdRegPath (AdGet $reg 'path')
        $v = Get-AdRegValue $hp[0] (AdGet $reg 'view' 64) $hp[1] (AdGet $reg 'name' 'Version')
        if ($v.exists -and (Test-Path -LiteralPath (Join-Path (Join-Path $root $v.value) $must))) { return (Join-Path $root $v.value) }
    }
    $pat = AdGet $vd 'pattern' '.'
    $d = @(Get-ChildItem -LiteralPath $root -Directory -ErrorAction SilentlyContinue | Where-Object {
            $_.Name -match $pat -and (-not $must -or (Test-Path -LiteralPath (Join-Path $_.FullName $must))) } |
        Sort-Object { $x = $null; if ([version]::TryParse($_.Name, [ref]$x)) { $x } else { [version]'0.0' } }, Name -Descending)
    if (-not $d) { throw "no version directory matching '$pat' with '$must' under $root" }
    $d[0].FullName
}
function Get-AdVersion($m) {
    $v = AdGet $m 'version'
    foreach ($s in @(AdGet $v 'sources' @())) {
        try {
            switch (AdGet $s 'source') {
                'registry' { $hp = Split-AdRegPath (AdGet $s 'path'); $r = Get-AdRegValue $hp[0] (AdGet $s 'view' 64) $hp[1] (AdGet $s 'name' 'Version'); if ($r.exists -and $r.value) { return "$($r.value)" } }
                'uninstall' { if ($script:Ad.Uninstall -and $script:Ad.Uninstall.DisplayVersion) { return $script:Ad.Uninstall.DisplayVersion } }
                'file' { $p = Expand-AdPath (AdGet $s 'path'); if (Test-Path -LiteralPath $p -PathType Leaf) { $fv = (Get-Item -LiteralPath $p).VersionInfo.FileVersion; if ($fv) { return ($fv -replace ',', '.' -replace '\s', '') } } }
                'dirname' { if ($script:Ad.Ver -ne $script:Ad.Root) { return (Split-Path -Leaf $script:Ad.Ver) } }
                'text' { $p = Expand-AdPath (AdGet $s 'path'); if (Test-Path -LiteralPath $p -PathType Leaf) { $t = [IO.File]::ReadAllText($p); if ($t -match (AdGet $s 'regex')) { return $Matches[1] } } }
            }
        } catch { }
    }
    $null
}
# Supported means: listed in version.supported.versions (the versions actually inspected), or, only when the
# manifest opts in with allowRange, inside min..max. An unknown version is never supported.
function Test-AdVersionSupported([string]$ver, $m) {
    $sup = AdGet (AdGet $m 'version') 'supported'
    if (-not $sup -or -not $ver) { return $false }
    $v = $ver.Trim(); $x = $null; $vx = [version]::TryParse(($v -replace '[^\d\.].*$', ''), [ref]$x)
    foreach ($s in @(AdGet $sup 'versions' @())) {
        $s = "$s".Trim(); if (-not $s) { continue }
        if ($s -ieq $v) { return $true }
        $y = $null; if ($vx -and $s -match '^[\d\.]+$' -and [version]::TryParse($s, [ref]$y) -and $x -eq $y) { return $true }
    }
    if ((AdGet $sup 'allowRange' $false) -and $vx) {
        $min = AdGet $sup 'min'; $max = AdGet $sup 'max'
        if ($min -and $max -and $x -ge [version]$min -and $x -le [version]$max) { return $true }
    }
    $false
}

# ------------------------------------------------------------------ journal
# journal.jsonl is append-only. A 'change' line is written BEFORE the mutation it describes (write-ahead): it
# carries the original state (first line for a key wins) and the state the tool is about to write ('after').
# An 'undone' line closes a key, so an interrupted -Uninstall never replays a finished restore.
function Protect-AdStateDir {
    $d = $script:Ad.StateDir
    if (-not (Test-Path -LiteralPath $d)) { New-Item -ItemType Directory -Path $d -Force | Out-Null }
    Invoke-AdNative icacls.exe @($d, '/inheritance:r', '/grant:r', '*S-1-5-18:(OI)(CI)F', '*S-1-5-32-544:(OI)(CI)F', '*S-1-5-32-545:(OI)(CI)RX') | Out-Null
}
function Add-AdJournalLine($e) {
    if (-not (Test-Path -LiteralPath $script:Ad.StateDir)) { Protect-AdStateDir }
    [IO.File]::AppendAllText($script:Ad.JournalPath, ((ConvertTo-Json -InputObject $e -Compress -Depth 10) + "`r`n"), (New-Object Text.UTF8Encoding $false))
}
# Active entries, oldest first: one per key, with the first-seen original and the latest after-state.
function Read-AdJournal {
    $active = [ordered]@{}
    if (Test-Path -LiteralPath $script:Ad.JournalPath) {
        foreach ($ln in [IO.File]::ReadAllLines($script:Ad.JournalPath)) {
            if (-not $ln.Trim()) { continue }
            $e = $ln | ConvertFrom-Json
            $k = [string](AdGet $e 'key')
            if ((AdGet $e 'kind' 'change') -eq 'undone') { if ($active.Contains($k)) { $active.Remove($k) }; continue }
            if ($active.Contains($k)) {
                $active[$k] | Add-Member -NotePropertyName after -NotePropertyValue (AdGet $e 'after') -Force
                $active[$k] | Add-Member -NotePropertyName data -NotePropertyValue (AdGet $e 'data') -Force
            } else {
                if ($null -eq $e.PSObject.Properties['after']) { $e | Add-Member -NotePropertyName after -NotePropertyValue $null }
                $active[$k] = $e
            }
        }
    }
    $list = New-Object System.Collections.Generic.List[object]
    foreach ($v in $active.Values) { $list.Add($v) }
    $list
}
function Get-AdAfterKey($after) { ConvertTo-Json -InputObject $after -Compress -Depth 10 }
function Write-AdJournal($item) {
    $ak = Get-AdAfterKey $item.After
    if ($script:Ad.JournalKeys.ContainsKey($item.Key) -and $script:Ad.JournalKeys[$item.Key] -eq $ak) { return }
    Add-AdJournalLine ([ordered]@{ kind = 'change'; ts = (Get-Date -Format s); app = $script:Ad.AppId; actionId = $item.ActionId; actionType = $item.ActionType
                                   prim = $item.Prim; key = $item.Key; desc = $item.Desc; reversible = $item.Reversible; evidence = $item.Evidence
                                   version = $script:Ad.Version; data = $item.Data; original = $item.Original; after = $item.After })
    $script:Ad.JournalKeys[$item.Key] = $ak
}

# ------------------------------------------------------------------ planning
function New-AdItem($a, [string]$prim, [string]$key, [string]$desc, $data, $original, $after) {
    [pscustomobject]@{ ActionId = AdGet $a 'id'; ActionType = AdGet $a 'type'; Prim = $prim; Key = $key; Desc = $desc
                       Data = $data; Original = $original; After = $after; Category = AdGet $a 'category'; Reversible = [bool](AdGet $a 'reversible' $true)
                       Reapply = [bool](AdGet $a 'reapply' $false); Evidence = AdGet $a 'evidence' }
}
function Get-AdRegSetItem($a, [string]$hive, $view, [string]$sub, [string]$name, $value, [string]$kind, [string]$desc) {
    $cur = Get-AdRegValue $hive $view $sub $name
    if ($cur.exists -and (Test-AdSame $cur.value $value)) { Say 'SKIP' "$desc (already set)"; return }
    New-AdItem $a 'regset' "reg:$hive$view\$sub|$name" $desc @{ hive = $hive; view = "$view"; sub = $sub; name = $name; value = $value; kind = $kind } $cur ([ordered]@{ exists = $true; value = $value; kind = $kind })
}
function Get-AdRegDelItem($a, [string]$hive, $view, [string]$parent, [string]$name) {
    $sub = "$parent\$name"
    $why = Get-AdRegKeyRefusal $sub; if ($why) { throw $why }
    if (-not (Test-AdRegKey $hive $view $sub)) { return }
    New-AdItem $a 'regdel' "regkey:$hive$view\$sub" "Delete registry key $hive\$sub" @{ hive = $hive; view = "$view"; parent = $parent; name = $name } @{ export = $null } ([ordered]@{ keyExists = $false })
}
