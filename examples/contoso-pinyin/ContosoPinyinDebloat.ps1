        }
        'firewall-block-program' {
            $dir = AdGet $a 'direction' 'Outbound'
            foreach ($p in (Get-AdTargets $a)) {
                Assert-AdPathSafe $p -NoTouch
                if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { Say 'SKIP' "$p not present"; continue }
                $h = ((Get-AdSha256Text $p.ToLowerInvariant()).Substring(0, 8))
                $name = "AppDebloat $($script:Ad.AppId) $id $([IO.Path]::GetFileName($p)) $h"
                if (@(Get-AdFirewallRules $name).Count) { Say 'SKIP' "firewall rule exists: $name"; continue }
                $grp = "AppDebloat-$($script:Ad.AppId)"
                $items.Add((New-AdItem $a 'firewall' "fw:$name" "Firewall: block $dir traffic of $p" @{ name = $name; program = $p; direction = $dir; group = $grp } @{ ruleExisted = $false } `
                    ([ordered]@{ name = $name; program = $p; group = $grp })))
            }
        }
        'hosts-block' {
            Say 'WARN' "$id`: hosts-block is discouraged (security products flag hosts edits); prefer firewall-block-program"
            if (-not (AdGet $a 'acknowledgeFlagging' $false)) { Say 'WARN' "$id`: skipped, set acknowledgeFlagging=true to use it"; break }
            $hosts = Join-Path $env:SystemRoot 'System32\drivers\etc\hosts'
            $text = if (Test-Path -LiteralPath $hosts) { [IO.File]::ReadAllText($hosts) } else { '' }
            $ms = 'microsoft\.com|windows\.com|windowsupdate|live\.com|msn\.com|bing\.com|office|azure|xbox|skype|msedge|msftncsi|msftconnecttest'
            $todo = @()
            foreach ($d in @(AdGet $a 'target' @())) {
                if ($d -notmatch '^[A-Za-z0-9\.\-]+$') { throw "bad domain $d" }
                if ($d -match $ms) { throw "hosts-block refuses Microsoft domain $d" }
                if ($text -notmatch ('(?m)^0\.0\.0\.0\s+' + [regex]::Escape($d) + '\s+# AppDebloat:' + [regex]::Escape($script:Ad.AppId))) { $todo += $d }
            }
            $lines = @($todo | ForEach-Object { "0.0.0.0 $_ # AppDebloat:$($script:Ad.AppId)" })
            if ($todo) { $items.Add((New-AdItem $a 'hosts' "hosts:$id" "hosts: sink $($todo -join ', ')" @{ domains = $todo; lines = $lines } @{} ([ordered]@{ lines = $lines }))) } else { Say 'SKIP' "$id`: hosts entries present" }
        }
        'preboot-file-edit' {
            $triples = @()
            $sec = AdGet $a 'section'; $set = AdGet $a 'set'
            if ($set) { foreach ($p in $set.PSObject.Properties) { $triples += , @($sec, $p.Name, [string]$p.Value) } }
            foreach ($ds in @(AdGet $a 'dropFromSections' @())) { if ($set) { foreach ($p in $set.PSObject.Properties) { $triples += , @($ds, $p.Name, $null) } } }
            $jobs = @(); $orig = @(); $diffs = @()
            foreach ($f in (Get-AdTargets $a)) {
                Assert-AdPathSafe $f
                if (-not (Test-Path -LiteralPath $f -PathType Leaf)) { continue }
                $r = Update-AdIni $f $triples $false
                if ($r.Diff.Count) { $jobs += [ordered]@{ file = $f; triples = $triples }; $orig += [ordered]@{ file = $f; triples = $r.Original }; $diffs += $r.Diff }
            }
            if (-not $jobs) { Say 'SKIP' "$id`: settings already in place (or no file)"; break }
            $task = "$($script:Ad.Prefix)Debloat-Preboot-$id"
            $body = New-AdPrebootScript $task $jobs $false
            $scr = Join-Path $script:Ad.StateDir "preboot-$id.ps1"
            if ((Test-Path -LiteralPath $scr) -and ([IO.File]::ReadAllText($scr) -eq $body) -and @(Get-AdTasks '\' $task).Count) {
                Say 'SKIP' "$id`: edit already scheduled for next boot ($task)"; break
            }
            $items.Add((New-AdItem $a 'preboot' "preboot:$id" "Schedule pre-logon edit ($task): $((@($diffs) | Select-Object -Unique) -join ', ')" @{ task = $task; script = $scr; jobs = $jobs } @{ jobs = $orig } `
                ([ordered]@{ task = $task; identity = (Get-AdPrebootIdentity $scr); jobs = $jobs })))
        }
        'hook' {
            $hn = AdGet $a 'hook'; $h = $script:Ad.Hooks[$hn]
            if (-not $h -or -not $h.Plan -or -not $h.Apply) { throw "hook '$hn' is not defined (needs Plan and Apply)" }
            foreach ($r in @(& $h.Plan $script:Ad $a)) {
                if ($null -eq $r) { continue }
                $items.Add((New-AdItem $a 'hook' "hook:$hn|$($r.Key)" $r.Desc @{ hook = $hn; data = $r.Data } $r.Original (AdGet $r 'After')))
            }
            if (-not $items.Count) { Say 'SKIP' "$id`: hook $hn reports nothing to change" }
        }
    }
    $items
}
function Get-AdSha256Text([string]$s) {
    $sha = [Security.Cryptography.SHA256]::Create()
    try { -join ($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($s)) | ForEach-Object { $_.ToString('x2') }) } finally { $sha.Dispose() }
}
function New-AdPrebootScript([string]$task, $jobs, [bool]$restore) {
    $json = (ConvertTo-Json -InputObject @($jobs) -Depth 6 -Compress) -replace "'", "''"
    $log = (Join-Path $script:Ad.StateDir 'preboot.log') -replace "'", "''"
    $tail = if ($restore) {
        # The state folder goes only after a clean -Uninstall (journal gone) and when no other restore is pending.
        "if (-not (Test-Path -LiteralPath '$($script:Ad.JournalPath -replace "'", "''")') -and -not (Get-ScheduledTask -TaskName '$($script:Ad.Prefix)Debloat-Restore-*' -ErrorAction SilentlyContinue)) { Remove-Item -LiteralPath '$($script:Ad.StateDir -replace "'", "''")' -Recurse -Force }"
    } else { '' }
    @"
`$ErrorActionPreference = 'Stop'
function Update-AdIni {${function:Update-AdIni}}
`$jobs = ConvertFrom-Json '$json'
`$ok = `$true
foreach (`$j in @(`$jobs)) {
    try { `$r = Update-AdIni `$j.file @(`$j.triples) `$true; Add-Content -LiteralPath '$log' "`$(Get-Date -Format s) $task `$(`$j.file) :: `$(`$r.Diff -join ', ')" }
    catch { `$ok = `$false; Add-Content -LiteralPath '$log' "`$(Get-Date -Format s) FAILED $task `$(`$j.file) :: `$(`$_.Exception.Message)" }
}
if (`$ok) {
    Unregister-ScheduledTask -TaskName '$task' -Confirm:`$false
    $tail
}
"@
}
function Register-AdPrebootTask([string]$task, [string]$scr, [string]$body) {
    Protect-AdStateDir
    [IO.File]::WriteAllText($scr, $body, (New-Object Text.UTF8Encoding $true))
    $act = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument "-NoProfile -ExecutionPolicy Bypass -File `"$scr`""
    $pri = New-ScheduledTaskPrincipal -UserId 'SYSTEM' -LogonType ServiceAccount -RunLevel Highest
    Register-ScheduledTask -TaskName $task -Action $act -Trigger (New-ScheduledTaskTrigger -AtStartup) -Principal $pri -Force `
        -Description "AppDebloat $($script:Ad.AppId): one-shot settings edit before logon, removes itself after success" | Out-Null
}

# ------------------------------------------------------------------ execution
function Get-AdBackupPath([string]$key) {
    $dir = Join-Path $script:Ad.StateDir 'backup'
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
    Join-Path $dir (Get-AdSha256Text $key).Substring(0, 16)
}
function Invoke-AdItem($it) {
    $d = $it.Data
    # Backups and exports happen before the journal line, so the journal always points at a real copy.
    $first = -not $script:Ad.JournalKeys.ContainsKey($it.Key)
    if ($first -and -not (Test-Path -LiteralPath $script:Ad.StateDir)) { Protect-AdStateDir }
    if ($first -and $it.Prim -eq 'regdel') {
        $dir = Join-Path $script:Ad.StateDir 'regkeys'; if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
        $file = Join-Path $dir ((Get-AdSha256Text $it.Key).Substring(0, 16) + '.reg')
        Invoke-AdNative reg.exe @('export', "$($d.hive)\$($d.parent)\$($d.name)", $file, '/y', "/reg:$($d.view)") | Out-Null
        $it.Original.export = $file
    }
    if ($first -and $it.Prim -eq 'file2dir' -and $d.backup -and (Test-Path -LiteralPath $d.path -PathType Leaf)) {
        $bk = (Get-AdBackupPath $it.Key) + '.bin'
        Copy-Item -LiteralPath $d.path -Destination $bk -Force
        if ((Get-AdSha256 $bk) -ne $it.Original.sha256) { throw "backup of $($d.path) does not match its hash; nothing changed" }
        $it.Original.backup = $bk
    }
    if ($first -and $it.Prim -eq 'dir2file' -and $d.backup -and (Test-Path -LiteralPath $d.path -PathType Container)) {
        $bk = (Get-AdBackupPath $it.Key) + '.dir'
        if (Test-Path -LiteralPath $bk) { Remove-Item -LiteralPath $bk -Recurse -Force }
        Copy-Item -LiteralPath $d.path -Destination $bk -Recurse -Force
        $n = @(Get-ChildItem -LiteralPath $bk -Recurse -File -Force).Count
        if ($n -ne $it.Original.fileCount) { throw "backup of $($d.path) holds $n of $($it.Original.fileCount) files; nothing changed" }
        $it.Original.backup = $bk
    }
    Write-AdJournal $it
    switch ($it.Prim) {
        'service' {
            Invoke-AdNative sc.exe @('config', $d.name, 'start=', 'disabled') | Out-Null
            if ($d.stop -and $it.Original.state -eq 'Running') { try { Stop-Service -Name $d.name -Force -ErrorAction Stop } catch { Say 'WARN' "service $($d.name) disabled but did not stop: $($_.Exception.Message)" } }
        }
        'task' { Disable-ScheduledTask -TaskPath $d.path -TaskName $d.name | Out-Null }
        'file2dir' {
            Assert-AdPathSafe $d.path
            foreach ($h in @($d.stopHosts)) { if ($h) { Stop-AdProcessByPath $h } }
            if ($d.path -like '*.exe') { Stop-AdProcessByPath $d.path }
            Set-AdPlaceholder $d.path 'Directory'
        }
        'dir2file' { Set-AdPlaceholder $d.path 'File' }
        'acl' {
            Assert-AdPathSafe $d.path
            if (-not (Test-Path -LiteralPath $d.path)) { New-Item -ItemType Directory -Path $d.path -Force | Out-Null }
            $isDir = Test-Path -LiteralPath $d.path -PathType Container
            if ($d.emptyFirst -and $isDir) { Get-ChildItem -LiteralPath $d.path -Force | ForEach-Object { Remove-Item -LiteralPath $_.FullName -Recurse -Force -Confirm:$false } }
            Set-AdDenyAce $d.path $d.sid ([int]$it.Original.addedRights) ([int]$d.inheritance)
        }
        'ifeo' { Set-AdRegValue 'HKLM' 64 "SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options\$($d.name)" 'Debugger' $script:Ad.IfeoTarget 'String' }
        'regset' { Set-AdRegValue $d.hive $d.view $d.sub $d.name $d.value $d.kind }
        'regdel' {
            $b = Open-AdHive $d.hive $d.view; $w = $null
            try { $w = $b.OpenSubKey($d.parent, $true) } catch { }
            $done = $false
            if ($w) { try { $w.DeleteSubKeyTree($d.name); $done = $true } catch { } finally { $w.Close() } }
            $b.Close()
            if (-not $done) {
                $r = Invoke-AdNative reg.exe @('delete', "$($d.hive)\$($d.parent)\$($d.name)", '/f', "/reg:$($d.view)") -NoThrow
                if ($r.Code) { Say 'WARN' "Cannot delete $($d.hive)\$($d.parent)\$($d.name) (likely owned by TrustedInstaller); left in place"; return 'warned' }
            }
        }
        'firewall' { New-NetFirewallRule -DisplayName $d.name -Group $d.group -Direction $d.direction -Action Block -Program $d.program | Out-Null }
        'hosts' {
            $hosts = Join-Path $env:SystemRoot 'System32\drivers\etc\hosts'
            [IO.File]::AppendAllText($hosts, "`r`n" + ($d.lines -join "`r`n") + "`r`n", [Text.Encoding]::ASCII)
        }
        'preboot' { Register-AdPrebootTask $d.task $d.script (New-AdPrebootScript $d.task $d.jobs $false) }
        'hook' { $h = $script:Ad.Hooks[$d.hook]; return (& $h.Apply $script:Ad $d.data $it) }
    }
}

# Undo one journal entry. Results: 'OK ...', 'SKIP ...' (already in its original state), 'GONE ...' (the object no
# longer exists), 'REINSTALL <path>', 'PENDING ...', 'WARN ...', 'CONFLICT ...'. The original is restored only when
# the current state still equals the state the tool wrote ('after'); anything else is a CONFLICT and is left alone.
function Invoke-AdUndo($e) {
    $d = $e.data; $o = $e.original; $af = AdGet $e 'after'
    if ($null -eq $af -and $e.prim -ne 'hook') { return "CONFLICT no after-state recorded (journal from an older engine): $($e.desc); check and restore it by hand" }
    switch ($e.prim) {
        'service' {
            $s = Get-AdService $d.name
            if (-not $s) { return "GONE service $($d.name) no longer exists" }
            $orig = "$(AdGet $o 'startMode')"
            if ("$($s.StartMode)" -ne 'Disabled') {
                if ("$($s.StartMode)" -eq $orig) { return "SKIP service $($d.name) is already $orig" }
                return "CONFLICT service $($d.name) start mode is now $($s.StartMode), not Disabled as the tool left it; left as is"
            }
            $m = @{ Auto = 'auto'; Manual = 'demand' }[$orig]
            if ($m -eq 'auto' -and (AdGet $o 'delayed' $false)) { $m = 'delayed-auto' }
            if (-not $m) { return "WARN service $($d.name): original start mode '$orig' is not restorable" }
            Invoke-AdNative sc.exe @('config', $d.name, 'start=', $m) | Out-Null
        }
        'task' {
            $t = @(Get-AdTasks $d.path $d.name) | Select-Object -First 1
            if (-not $t) { return "GONE task $($d.path)$($d.name) no longer exists" }
            if ((Get-AdTaskIdentity $t) -ne (AdGet $af 'actions')) { return "CONFLICT task $($d.path)$($d.name) now runs '$(Get-AdTaskIdentity $t)', not the action it had when disabled; left as is" }
            if ("$($t.State)" -ne 'Disabled') { return "SKIP task $($d.path)$($d.name) is enabled already" }
            if ((AdGet $o 'state') -ne 'Disabled') { Enable-ScheduledTask -TaskPath $d.path -TaskName $d.name | Out-Null }
        }
        'file2dir' {
            $p = $d.path
            if (Test-Path -LiteralPath $p -PathType Leaf) { return "SKIP $p is a file again (restored by the vendor)" }
            if (Test-Path -LiteralPath $p -PathType Container) {
                if (@(Get-ChildItem -LiteralPath $p -Force).Count) { return "CONFLICT placeholder folder $p is no longer empty; left as is" }
                Remove-Item -LiteralPath $p -Force
            }
            if (-not (AdGet $o 'existed')) { return }
            $bk = AdGet $o 'backup'
            if ($bk -and (Test-Path -LiteralPath $bk -PathType Leaf) -and (Get-AdSha256 $bk) -eq (AdGet $o 'sha256')) {
                Copy-Item -LiteralPath $bk -Destination $p; return "OK restored $p from backup"
            }
            return "REINSTALL $p"
        }
        'dir2file' {
            $p = $d.path
            if (Test-Path -LiteralPath $p -PathType Container) { return "SKIP $p is a folder again (restored by the vendor)" }
            if (Test-Path -LiteralPath $p -PathType Leaf) {
                $f = Get-Item -LiteralPath $p -Force
                if ($f.Length -ne 0) { return "CONFLICT placeholder file $p now has content; left as is" }
                $f.IsReadOnly = $false; Remove-Item -LiteralPath $p -Force
            }
            if (-not (AdGet $o 'existed')) { return }
            $bk = AdGet $o 'backup'
            if ($bk -and (Test-Path -LiteralPath $bk -PathType Container) -and @(Get-ChildItem -LiteralPath $bk -Recurse -File -Force).Count -eq (AdGet $o 'fileCount')) {
                Copy-Item -LiteralPath $bk -Destination $p -Recurse; return "OK restored $p from backup"
            }
            return "REINSTALL $p\"
        }
        'acl' {
            $p = $d.path
            if (-not (Test-Path -LiteralPath $p)) { return "GONE $p no longer exists" }
            $added = [int](AdGet $o 'addedRights' 0); $inh = [int](AdGet $d 'inheritance' 0)
            $have = (Get-AdDenyRights $p $d.sid $inh) -band $added
            if ($have -eq 0) { $r = "SKIP deny entry on $p already removed" }
            elseif ($have -ne $added) { return "CONFLICT deny entry for $($d.sid) on $p was changed since the tool added it; left as is" }
            else { Set-AdDenyAce $p $d.sid $added $inh -Remove; $r = $null }
            if (-not (AdGet $o 'existed') -and (Test-Path -LiteralPath $p -PathType Container) -and -not @(Get-ChildItem -LiteralPath $p -Force).Count) { Remove-Item -LiteralPath $p -Force }
            $out = @(); if ($r) { $out += $r }
            if ($d.emptyFirst -and (AdGet $o 'entries' 0)) { $out += "REINSTALL contents of $p" }
            return $out
        }
        'ifeo' {
            $ifeo = 'SOFTWARE\Microsoft\Windows NT\CurrentVersion\Image File Execution Options'
            $cur = Get-AdRegValue 'HKLM' 64 "$ifeo\$($d.name)" 'Debugger'
            if ($cur.exists -and $cur.value -ne (AdGet $af 'debugger')) { return "CONFLICT IFEO $($d.name) Debugger is now '$($cur.value)'; left as is" }
            $b = Open-AdHive 'HKLM' 64; $k = $b.OpenSubKey("$ifeo\$($d.name)", $true)
            if ($k) {
                if ($cur.exists) { $k.DeleteValue('Debugger') }
                $empty = ($k.ValueCount -eq 0 -and $k.SubKeyCount -eq 0); $k.Close()
                if ($empty -and -not (AdGet $o 'keyExisted')) { $pk = $b.OpenSubKey($ifeo, $true); $pk.DeleteSubKey($d.name); $pk.Close() }
            }
            $b.Close()
            if (-not $cur.exists) { return "SKIP IFEO $($d.name) Debugger already removed" }
        }
        'regset' {
            $cur = Get-AdRegValue $d.hive $d.view $d.sub $d.name
            $isOrig = if (AdGet $o 'exists') { $cur.exists -and (Test-AdSame $cur.value (AdGet $o 'value')) } else { -not $cur.exists }
            if ($isOrig) { return "SKIP $($d.hive)\$($d.sub) $($d.name) already has its original value" }
            if (-not ($cur.exists -and (Test-AdSame $cur.value (AdGet $af 'value')))) {
                $now = if ($cur.exists) { "'$(@($cur.value) -join ',')'" } else { 'absent' }
                return "CONFLICT $($d.hive)\$($d.sub) $($d.name) is now $now, not '$(@(AdGet $af 'value') -join ',')' as the tool wrote it; left as is"
            }
            if (AdGet $o 'exists') { Set-AdRegValue $d.hive $d.view $d.sub $d.name (AdGet $o 'value') (AdGet $o 'kind') }
            else {
                $b = Open-AdHive $d.hive $d.view; $k = $b.OpenSubKey($d.sub, $true)
                if ($k) { $k.DeleteValue($d.name); $empty = ($k.ValueCount -eq 0 -and $k.SubKeyCount -eq 0); $k.Close()
                          if ($empty -and -not (AdGet $o 'keyExisted')) { $b.DeleteSubKey($d.sub, $false) } }
                $b.Close()
            }
        }
        'regdel' {
            $key = "$($d.hive)\$($d.parent)\$($d.name)"
            if (Test-AdRegKey $d.hive $d.view "$($d.parent)\$($d.name)") { return "CONFLICT $key exists again; the saved export is not imported over it" }
            $f = AdGet $o 'export'
            if (-not $f -or -not (Test-Path -LiteralPath $f)) { return "WARN no export for $key" }
            Invoke-AdNative reg.exe @('import', $f, "/reg:$($d.view)") | Out-Null
        }
        'firewall' {
            $rules = @(Get-AdFirewallRules $d.name)
            if (-not $rules) { return "SKIP firewall rule $($d.name) already removed" }
            $res = @()
            foreach ($r in $rules) {
                $prog = (Get-NetFirewallApplicationFilter -AssociatedNetFirewallRule $r -ErrorAction Stop).Program
                if ("$($r.Group)" -eq (AdGet $af 'group') -and $prog -ieq (AdGet $af 'program')) { Remove-NetFirewallRule -Name $r.Name -ErrorAction Stop }
                else { $res += "CONFLICT firewall rule '$($d.name)' ($($r.Name)) now has group '$($r.Group)' and program '$prog'; left as is" }
            }
            return $res
        }
        'hosts' {
            $hosts = Join-Path $env:SystemRoot 'System32\drivers\etc\hosts'
            if (-not (Test-Path -LiteralPath $hosts)) { return 'GONE hosts file is missing' }
            $enc = [Text.Encoding]::GetEncoding(28591)   # byte-preserving
            $text = $enc.GetString([IO.File]::ReadAllBytes($hosts))
            $nl = if ($text -match "`r`n") { "`r`n" } else { "`n" }
            $lines = New-Object System.Collections.Generic.List[string]; foreach ($l in [regex]::Split($text, '\r?\n')) { $lines.Add($l) }
            $removed = 0
            foreach ($w in @(AdGet $af 'lines' @())) { $i = $lines.IndexOf([string]$w); if ($i -ge 0) { $lines.RemoveAt($i); $removed++ } }
            if (-not $removed) { return 'SKIP hosts lines already removed' }
            [IO.File]::WriteAllBytes($hosts, $enc.GetBytes(($lines -join $nl)))
        }
        'preboot' {
            $t = @(Get-AdTasks '\' $d.task) | Select-Object -First 1
            if ($t) {
                if ((Get-AdTaskIdentity $t) -ne (AdGet $af 'identity')) { return "CONFLICT task $($d.task) now runs '$(Get-AdTaskIdentity $t)'; left as is" }
                Unregister-ScheduledTask -TaskName $d.task -Confirm:$false; return 'OK pending pre-logon edit cancelled'
            }
            # The edit ran. Restore only files whose values are still exactly what the tool wrote.
            $jobs = @(); $res = @()
            foreach ($oj in @(AdGet $o 'jobs' @())) {
                $wj = @(@($d.jobs) | Where-Object { $_.file -eq $oj.file }) | Select-Object -First 1
                if (-not (Test-Path -LiteralPath $oj.file -PathType Leaf)) { $res += "SKIP $($oj.file) no longer exists"; continue }
                if (-not $wj) { $res += "CONFLICT no written values recorded for $($oj.file)"; continue }
                $chk = Update-AdIni $oj.file @($wj.triples) $false
                if ($chk.Diff.Count) { $res += "CONFLICT $($oj.file) changed since the edit ($($chk.Diff -join ', ')); left as is"; continue }
                $jobs += $oj
            }
            if ($jobs) {
                $task = "$($script:Ad.Prefix)Debloat-Restore-$($e.actionId)"
                $scr = Join-Path $script:Ad.StateDir "restore-$($e.actionId).ps1"
                Register-AdPrebootTask $task $scr (New-AdPrebootScript $task $jobs $true)
                $script:Ad.KeepState = $true
                $res += "PENDING original settings are restored before the next logon ($task)"
            }
            return $res
        }
        'watchtask' {
            $t = @(Get-AdTasks '\' $d.name) | Select-Object -First 1
            if (-not $t) { return "GONE task $($d.name) no longer exists" }
            if ((Get-AdTaskIdentity $t) -ne (AdGet $af 'identity')) { return "CONFLICT task $($d.name) now runs '$(Get-AdTaskIdentity $t)', not what -Install registered; left as is" }
            Unregister-ScheduledTask -TaskName $d.name -Confirm:$false
        }
        'hook' {
            $h = $script:Ad.Hooks[$d.hook]
            if (-not $h -or -not $h.Undo) { return "WARN hook $($d.hook) has no Undo: $($e.desc)" }
            return (& $h.Undo $script:Ad $d.data $o $e)
        }
        default { return "WARN unknown journal entry type '$($e.prim)': $($e.desc)" }
    }
}

# ------------------------------------------------------------------ install / uninstall
function Register-AdWatchTask([string]$installed) {
    $user = [Security.Principal.WindowsIdentity]::GetCurrent().Name
    $act = New-ScheduledTaskAction -Execute 'conhost.exe' -Argument "--headless powershell.exe -NoProfile -ExecutionPolicy Bypass -File `"$installed`" -Auto"
    $logon = New-ScheduledTaskTrigger -AtLogOn -User $user
    $every = New-ScheduledTaskTrigger -Daily -At '00:00'
    $every.Repetition = (New-ScheduledTaskTrigger -Once -At '00:00' -RepetitionInterval (New-TimeSpan -Hours 6) -RepetitionDuration (New-TimeSpan -Days 1)).Repetition
    $pri = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Highest
    $set = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -ExecutionTimeLimit (New-TimeSpan -Minutes 15)
    Register-ScheduledTask -TaskName $script:Ad.WatchTask -Action $act -Trigger @($logon, $every) -Principal $pri -Settings $set -Force `
        -Description "AppDebloat $($script:Ad.AppId): re-confirms blocking actions at logon and every 6 hours" | Out-Null
}
# Files this tool writes into its state folder; anything else found there is left in place.
function Remove-AdStateFiles([switch]$KeepRestore) {
    $dir = $script:Ad.StateDir
    if (-not (Test-Path -LiteralPath $dir)) { return }
    $own = @('journal.jsonl', 'options.json', 'state.json', 'auto.log', 'history.log', 'regkeys', 'backup', "$($script:Ad.Prefix)Debloat.ps1")
    foreach ($f in @(Get-ChildItem -LiteralPath $dir -Force)) {
        $mine = ($own -contains $f.Name) -or ($f.Name -like 'preboot-*.ps1') -or ($f.Name -like '*.adtmp') -or
                (-not $KeepRestore -and ($f.Name -like 'restore-*.ps1' -or $f.Name -eq 'preboot.log'))
        if ($mine) { Remove-Item -LiteralPath $f.FullName -Recurse -Force }
    }
    if ($KeepRestore) { Say 'OK' 'State folder is removed by the restore task after the next boot'; return }
    if (@(Get-ChildItem -LiteralPath $dir -Force).Count) { Say 'INFO' "Left $dir in place: it holds files this tool did not write" }
    else { Remove-Item -LiteralPath $dir -Force; Say 'OK' "Removed $dir" }
}
# Returns the number of entries that were not cleanly undone (WARN, CONFLICT or failure).
function Invoke-AdUninstall {
    $journal = @(Read-AdJournal)
    $reinstall = @(); $issues = New-Object System.Collections.Generic.List[string]
    for ($i = $journal.Count - 1; $i -ge 0; $i--) {
        $e = $journal[$i]
        $close = [ordered]@{ kind = 'undone'; ts = (Get-Date -Format s); key = $e.key }
        if (-not (AdGet $e 'reversible' $true)) { Say 'INFO' "not reversible, left as is: $($e.desc)"; Add-AdJournalLine $close; continue }
        $bad = $null; $res = @()
        try { $res = @(Invoke-AdUndo $e) } catch { $bad = "FAIL $($_.Exception.Message)"; Say 'FAIL' "undo $($e.desc) :: $($_.Exception.Message)" }
        foreach ($x in $res) {
            $s = "$x"; if (-not $s) { continue }
            if ($s -like 'REINSTALL *') { $reinstall += $s.Substring(10) }
            elseif ($s -like 'WARN *') { Say 'WARN' $s.Substring(5); $bad = $s }
            elseif ($s -like 'CONFLICT *') { Say 'CONFLICT' $s.Substring(9); $bad = $s }
            elseif ($s -like 'PENDING *') { Say 'OK' $s.Substring(8) }
            elseif ($s -like 'OK *') { Say 'OK' $s.Substring(3) }
            else { Say 'INFO' $s }
        }
        if ($bad) { $issues.Add("$($e.desc): $bad") }
        else { Add-AdJournalLine $close; Say 'OK' "undone: $($e.desc)" }
    }
    if ($issues.Count) {
        Write-Host ''
        Write-Host "Uninstall is NOT complete: $($issues.Count) item(s) were left as they are. The journal and $($script:Ad.StateDir) are kept." -ForegroundColor Red
        foreach ($x in $issues) { Write-Host "  - $x" }
        Write-Host 'Resolve each item by hand (restore the recorded value, or put back the state the tool wrote), then run -Uninstall again.'
        Write-Host 'Items already undone are recorded as such and are not replayed.'
    } else { Remove-AdStateFiles -KeepRestore:$script:Ad.KeepState }
    if ($reinstall) {
        Write-Host ''
        Write-Host "These vendor files were removed without a usable backup and come back only by reinstalling $($script:Ad.Name) over the top:"
        $reinstall | Select-Object -Unique | ForEach-Object { Write-Host "  $_" }
    }
    $issues.Count
}
function Write-AdHistory([string]$text) {
    if (-not (Test-Path -LiteralPath $script:Ad.StateDir)) { return }
    [IO.File]::AppendAllText((Join-Path $script:Ad.StateDir 'history.log'), ("{0} engine {1} {2} {3}`r`n" -f (Get-Date -Format s), $script:AdEngineVersion, $script:Ad.AppId, $text), (New-Object Text.UTF8Encoding $false))
}

# ------------------------------------------------------------------ entry point
# Mode: Plan | Apply | Install | Uninstall | Auto. Returns the process exit code:
# 0 ok, 1 at least one FAIL (or an Uninstall left items behind), 2 refused before any change (more than one mode,
# not elevated, invalid manifest, not installed, identity check failed, unsupported version).
function Invoke-AppDebloat {
    param([Parameter(Mandatory)][string]$ManifestJson, [hashtable]$Hooks = @{}, [string]$Mode = 'Plan',
          [hashtable]$Options = @{}, [string]$InstallRoot, [switch]$Force, [string]$ScriptPath)
    if (@('Plan', 'Apply', 'Install', 'Uninstall', 'Auto') -notcontains $Mode) { Write-Host "[FAIL] unknown mode '$Mode'. Nothing was changed." -ForegroundColor Red; return 2 }
    $m = $ManifestJson | ConvertFrom-Json
    $script:Ad = @{ Changes = 0; Failures = 0; Warnings = 0; Conflicts = 0; WarnLines = (New-Object System.Collections.Generic.List[string]); Hooks = $Hooks
                    Manifest = $m; Vars = @{}; Root = $null; Ver = $null; Uninstall = $null; KeepState = $false; Options = $Options
                    Bases = (New-Object System.Collections.Generic.List[string]); RealBases = @{}; CoreFiles = @(); CoreProcs = @(); CoreSvcs = @(); Restartable = @()
                    JournalKeys = @{}; Version = $null; AppId = 'unknown'; StateDir = $null }
    try { Test-AdManifest $m } catch { Say 'FAIL' $_.Exception.Message; return 2 }
    $Ad.AppId = $m.id; $Ad.Name = $m.name; $Ad.Prefix = $m.taskPrefix
    $Ad.StateDir = Join-Path $env:ProgramData "AppDebloat\$($m.id)"
    $Ad.JournalPath = Join-Path $Ad.StateDir 'journal.jsonl'
    $Ad.WatchTask = "$($m.taskPrefix)Debloat-Watch"
    $Ad.IfeoTarget = Join-Path $env:SystemRoot "System32\AppDebloat-blocked\$($m.id).exe"   # never exists
    $Ad.OutOfProcessOnly = ((AdGet $m 'riskTier' 'normal') -eq 'out-of-process-only')
    $optFile = Join-Path $Ad.StateDir 'options.json'

    if ($Mode -ne 'Plan' -and -not (Test-AdIsAdmin)) { Say 'FAIL' "-$Mode needs an elevated (Administrator) PowerShell. Nothing was changed."; return 2 }
    $stopLog = { if ($Mode -eq 'Auto') { try { Stop-Transcript | Out-Null } catch { } } }
    if ($Mode -eq 'Auto') {
        if (Test-Path -LiteralPath $optFile) {
            $saved = [IO.File]::ReadAllText($optFile) | ConvertFrom-Json
            foreach ($p in $saved.PSObject.Properties) { $Options[$p.Name] = [bool]$p.Value }
        }
        if (Test-Path -LiteralPath $Ad.StateDir) { try { Start-Transcript -LiteralPath (Join-Path $Ad.StateDir 'auto.log') -Force | Out-Null } catch { } }
    }
    Initialize-AdForbidden
    try {
        $rr = Resolve-AdInstallRoot $m $InstallRoot; $Ad.Root = $rr[0]
        $Ad.RealRoot = Add-AdBase $Ad.Root 'install root'
        $Ad.Ver = Resolve-AdVersionDir $m $Ad.Root
        $pv = AdGet $m 'pathVars'; $pvp = if ($pv) { @($pv.PSObject.Properties) } else { @() }
        foreach ($p in $pvp) {
            $ev = AdGet $p.Value 'envVar'; $val = if ($ev -and [Environment]::GetEnvironmentVariable($ev)) { [Environment]::GetEnvironmentVariable($ev) } else { AdGet $p.Value 'default' }
            $Ad.Vars[$p.Name] = Get-AdNormal (Expand-AdPath $val)
        }
        foreach ($b in @(AdGet $m 'allowedRoots' @())) { [void](Add-AdBase (Get-AdNormal (Expand-AdPath $b)) "allowedRoots entry '$b'") }
        $core = AdGet $m 'core'
        $Ad.CoreFiles = @(); foreach ($f in @(AdGet $core 'files' @())) { foreach ($x in (Resolve-AdTargets $f)) { $Ad.CoreFiles += (Get-AdNormal $x) } }
        $Ad.CoreProcs = @(@(AdGet $core 'processes' @()) | ForEach-Object { $_.ToLowerInvariant() })
        $Ad.CoreSvcs = @(@(AdGet $core 'services' @()) | ForEach-Object { $_.ToLowerInvariant() })
        $Ad.Restartable = @(@(AdGet $core 'restartable' @()) | ForEach-Object { $_.ToLowerInvariant() })
    } catch {
        if ($Mode -eq 'Uninstall') { Say 'WARN' "$($_.Exception.Message) (continuing: the journal alone drives -Uninstall)" }
        else {
            Say 'FAIL' $_.Exception.Message
            if ($Mode -eq 'Auto') { Write-AdHistory "REFUSED: nothing changed. WARN: $($_.Exception.Message)" }
            & $stopLog; return 2
        }
    }
    if ($Mode -eq 'Uninstall') {
        Write-Host "$($m.name) debloat: UNINSTALL (journal replay in reverse)"
        $left = Invoke-AdUninstall
        if ($left -or $Ad.Failures) { return 1 }
        return 0
    }

    $Ad.Version = Get-AdVersion $m
    $supported = Test-AdVersionSupported $Ad.Version $m
    $fingerprint = "$($Ad.Version)|$(Split-Path -Leaf $Ad.Ver)"
    $statePath = Join-Path $Ad.StateDir 'state.json'
    $prevFp = $null; if (Test-Path -LiteralPath $statePath) { $prevFp = AdGet ([IO.File]::ReadAllText($statePath) | ConvertFrom-Json) 'fingerprint' }
    $sup = AdGet (AdGet $m 'version') 'supported'
    $supText = (@(AdGet $sup 'versions' @()) -join ', ') + $(if (AdGet $sup 'allowRange' $false) { " or $(AdGet $sup 'min')..$(AdGet $sup 'max')" } else { '' })

    Write-Host ("App           : {0} ({1})" -f $m.name, $m.id)
    Write-Host ("Install root  : {0}   [from {1}]" -f $Ad.Root, $rr[1])
    if ($Ad.RealRoot -ine $Ad.Root) { Write-Host "Real path     : $($Ad.RealRoot)" }
    if ($Ad.Ver -ne $Ad.Root) { Write-Host "Version dir   : $($Ad.Ver)" }
    Write-Host ("Version       : {0}{1}" -f $(if ($Ad.Version) { $Ad.Version } else { 'unknown' }), $(if ($supported) { '' } else { "  (NOT SUPPORTED; supported: $supText)" }))
    Write-Host ("Mode          : {0}" -f $(if ($Mode -eq 'Plan') { 'dry run (add -Apply to change things)' } elseif ($Mode -eq 'Auto') { 'AUTO (blocking actions only)' } else { $Mode.ToUpper() }))
    $on = @($Options.Keys | Where-Object { $Options[$_] }); if ($on) { Write-Host "Options       : $($on -join ', ')" }
    if (-not $Ad.Version) { Say 'WARN' 'No version.sources entry returned a version, so -Apply/-Install/-Auto will refuse. Check the manifest sources against the installed files before going further.' }
    Write-Host ''
    if (-not $supported) {
        $vt = if ($Ad.Version) { "version $($Ad.Version)" } else { 'the version could not be read; it' }
        $msg = "$vt is not one this manifest was built from (supported: $supText)"
        if ($Mode -eq 'Plan') { Say 'WARN' "$msg; the plan below may be stale" }
        elseif ($Force) { Say 'WARN' "$msg; continuing because -Force was given" }
        elseif ($Mode -eq 'Auto') {
            Say 'WARN' "$msg. Nothing was changed; re-run inventory (P1 to P3) and rebuild, or run once with -Apply -Force"
            Write-AdHistory "$fingerprint REFUSED: 0 change(s). WARN: $msg"
            & $stopLog; return 2
        } else {
            Say 'FAIL' "$msg. Nothing was changed: re-run inventory (P1 to P3) and add it to version.supported.versions, or pass -Force"
            return 2
        }
    }
    if ($Mode -eq 'Auto' -and $prevFp -and $prevFp -ne $fingerprint) { Say 'WARN' "version fingerprint changed $prevFp -> ${fingerprint}: only blocking actions are re-applied; re-run inventory (P1 to P3)" }

    $Ad.JournalKeys = @{}; foreach ($e in @(Read-AdJournal)) { $Ad.JournalKeys[$e.key] = Get-AdAfterKey (AdGet $e 'after') }
    if ($Mode -eq 'Install') {
        if (-not $ScriptPath) { Say 'FAIL' '-Install needs the script path'; return 2 }
        $wkey = "watchtask:$($Ad.WatchTask)"
        if (@(Get-AdTasks '\' $Ad.WatchTask).Count -and -not $Ad.JournalKeys.ContainsKey($wkey)) {
            Say 'FAIL' "a scheduled task named $($Ad.WatchTask) exists that this tool did not register; not replacing it. Nothing was changed."; return 2
        }
        Protect-AdStateDir
        $installed = Join-Path $Ad.StateDir "$($m.taskPrefix)Debloat.ps1"
        if ($ScriptPath -ne $installed) { Copy-Item -LiteralPath $ScriptPath -Destination $installed -Force }
        $opt = [ordered]@{}; foreach ($o in @(AdGet $m 'options' @())) { $opt[$o.name] = [bool]$Options[$o.name] }
        [IO.File]::WriteAllText($optFile, ($opt | ConvertTo-Json), (New-Object Text.UTF8Encoding $false))
        $wi = [pscustomobject]@{ ActionId = 'install'; ActionType = 'watch-task'; Prim = 'watchtask'; Key = $wkey; Desc = "Scheduled task $($Ad.WatchTask)"
                                 Reversible = $true; Evidence = 'observed'; Data = @{ name = $Ad.WatchTask }; Original = @{ existed = $false }
                                 After = [ordered]@{ identity = (Get-AdWatchIdentity $installed) } }
        Write-AdJournal $wi
        Register-AdWatchTask $installed
        Say 'OK' "Installed to $installed and registered task $($Ad.WatchTask) (logon + every 6 h)"
        Write-Host ''
    }

    # Plan: every active action is resolved to concrete items first; the same list is printed and then executed.
    # An action backed only by inferred or hypothesis evidence is inactive unless its 'when' option is given.
    $items = New-Object System.Collections.Generic.List[object]
    $inactive = New-Object System.Collections.Generic.List[string]
    foreach ($a in @(AdGet $m 'actions' @())) {
        $w = AdGet $a 'when'; $u = AdGet $a 'unless'; $ev = AdGet $a 'evidence'
        if ($Mode -eq 'Auto' -and -not (AdGet $a 'reapply' $false)) { continue }
        if ($script:AdEvidenceActive -notcontains $ev -and -not $Options[$w]) {
            $note = AdGet $a 'evidenceNote' ''
            $inactive.Add(("[{0}] {1}, {2}: evidence is {3}{4}. Enable with -{5}" -f (AdGet $a 'id'), (AdGet $a 'type'), (AdGet $a 'category'), $ev, $(if ($note) { " ($note)" } else { '' }), $w))
            continue
        }
        if ($w -and -not $Options[$w]) { continue }
        if ($u -and $Options[$u]) { continue }
        try { foreach ($it in (Get-AdActionPlan $a)) { $items.Add($it) } }
        catch { Say 'FAIL' "$(AdGet $a 'id'): $($_.Exception.Message)" }
    }
    Write-Host ''
    Write-Host ("Plan: {0} change(s)" -f $items.Count)
    $n = 0
    foreach ($it in $items) {
        $n++
        Write-Host ('  {0,3}. [{1}] {2}' -f $n, $it.ActionId, $it.Desc) -ForegroundColor Yellow
        Write-Host ('       {0}, {1}, evidence {2}{3}' -f $it.ActionType, $it.Category, $it.Evidence, $(if ($it.Reapply) { ', reapply' } else { '' })) -ForegroundColor DarkGray
    }
    if ($inactive.Count) {
        Write-Host ''
        Write-Host ("Inactive: {0} action(s) not backed by observed or anchored evidence (they run only with their option)" -f $inactive.Count)
        foreach ($x in $inactive) { Say 'INACTIVE' $x }
    }
    Write-Host ''
    $apply = ($Mode -ne 'Plan')
    if ($apply -and $items.Count) {
        foreach ($it in $items) {
            try {
                $r = Invoke-AdItem $it
                if (@($r) -contains 'warned') { continue }      # WARN-only steps are not changes
                $Ad.Changes++; Say 'OK' $it.Desc
            } catch { Say 'FAIL' "$($it.Desc) :: $($_.Exception.Message)" }
        }
    }
    if ($apply -and (Test-Path -LiteralPath $Ad.StateDir)) {
        [IO.File]::WriteAllText($statePath, ([ordered]@{ fingerprint = $fingerprint; lastRun = (Get-Date -Format s); engine = $script:AdEngineVersion } | ConvertTo-Json), (New-Object Text.UTF8Encoding $false))
    }
    if ($Mode -eq 'Auto') {
        $warn = if ($Ad.WarnLines.Count) { ' WARN: ' + (($Ad.WarnLines | Select-Object -Unique) -join ' | ') } else { '' }
        Write-AdHistory ("{0}: {1} change(s), {2} failure(s){3}" -f $fingerprint, $Ad.Changes, $Ad.Failures, $warn)
        & $stopLog
    }
    if (-not $apply) { Write-Host "$($items.Count) change(s) planned. Run again with -Apply in an elevated PowerShell to execute exactly this plan." }
    else {
        Write-Host "$($Ad.Changes) change(s) made, $($Ad.Warnings) warning(s), $($Ad.Failures) failure(s)."
        if (@($items | Where-Object { $_.Prim -eq 'preboot' })) { Write-Host 'Reboot: a pre-logon settings edit is scheduled.' }
    }
    if ($Ad.Failures) { return 1 }
    0
}

# ------------------------------------------------------------------ build step
# Inlines this engine, the manifest and optional hooks into the template: one self-contained per-app script.
function New-AppScript {
    param([Parameter(Mandatory)][string]$ManifestPath, [string]$HooksPath, [Parameter(Mandatory)][string]$OutFile,
          [string]$TemplatePath, [string]$EnginePath = $script:AdEngineSource)
    if (-not $EnginePath -or (Split-Path -Leaf $EnginePath) -ne 'DebloatEngine.ps1') { throw 'pass -EnginePath (path to DebloatEngine.ps1)' }
    if (-not $TemplatePath) { $TemplatePath = Join-Path (Split-Path (Split-Path $EnginePath -Parent) -Parent) 'templates\app-debloat.template.ps1' }
    $json = [IO.File]::ReadAllText($ManifestPath).Trim()
    $m = $json | ConvertFrom-Json
    Test-AdManifest $m
    if ($json -match "(?m)^'@") { throw "manifest JSON must not contain a line starting with '@" }
    $hooks = if ($HooksPath) { [IO.File]::ReadAllText($HooksPath).Trim() } else { '# (no app-specific hooks)' }
    $engine = ([IO.File]::ReadAllText($EnginePath) -replace '(?m)^#Requires.*\r?\n', '').Trim()
    $optParams = @(); $optHelp = @()
    foreach ($o in @(AdGet $m 'options' @())) {
        $optParams += "    [switch]`$$($o.name),"
        $gated = @(@(AdGet $m 'actions' @()) | Where-Object { (AdGet $_ 'when') -eq $o.name -and $script:AdEvidenceActive -notcontains (AdGet $_ 'evidence') } |
            ForEach-Object { "$(AdGet $_ 'id') ($(AdGet $_ 'evidence'))" })
        $h = AdGet $o 'help' ''
        if ($gated) { $h += " Enables action(s) not yet backed by observed evidence: $($gated -join ', ')." }
        $optHelp += ".PARAMETER $($o.name)", "  $h"
    }
    $t = [IO.File]::ReadAllText($TemplatePath)
    $t = $t.Replace('@@APP_NAME@@', $m.name).Replace('@@APP_PREFIX@@', $m.taskPrefix).Replace('@@APP_ID@@', $m.id)
    $t = $t.Replace('    #@@OPTION_PARAMS@@', ($optParams -join "`r`n"))
    $t = $t.Replace('#@@OPTION_HELP@@', ($optHelp -join "`r`n"))
    $t = $t.Replace('#@@MANIFEST@@', $json)
    $t = $t.Replace('#@@HOOKS@@', $hooks)
    $t = $t.Replace('#@@ENGINE@@', "# ---- inlined DebloatEngine.ps1 $($script:AdEngineVersion) ----`r`n$engine`r`n# ---- end of engine ----")
    $t = $t -replace "(?<!`r)`n", "`r`n"
    [IO.File]::WriteAllText($OutFile, $t, (New-Object Text.UTF8Encoding $true))
    $errs = $null; [void][Management.Automation.Language.Parser]::ParseFile($OutFile, [ref]$null, [ref]$errs)
    if ($errs) { throw "built script does not parse: $($errs[0].Message) (line $($errs[0].Extent.StartLineNumber))" }
    $OutFile
}
# ---- end of engine ----

if (-not (Get-Command Invoke-AppDebloat -ErrorAction SilentlyContinue)) {
    throw 'This is the unbuilt template. Build a per-app script with New-AppScript (scripts/DebloatEngine.ps1).'
}
$mode = Resolve-AdMode -Apply:$Apply -Install:$Install -Uninstall:$Uninstall -Auto:$Auto
if (-not $mode) { exit 2 }
$opts = @{}
$optProp = ($ManifestJson | ConvertFrom-Json).PSObject.Properties['options']
if ($optProp) { foreach ($o in @($optProp.Value)) { $opts[$o.name] = [bool](Get-Variable -Name $o.name -ValueOnly) } }
$code = @(Invoke-AppDebloat -ManifestJson $ManifestJson -Hooks $Hooks -Mode $mode -Options $opts `
    -InstallRoot $InstallRoot -Force:$Force -ScriptPath $PSCommandPath)[-1]
exit $code
