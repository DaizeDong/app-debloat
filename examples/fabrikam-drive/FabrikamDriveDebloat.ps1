#Requires -Version 5.1
<#
.SYNOPSIS
  Debloat Fabrikam Drive: block its ads, popups, AI add-ons, promotions, telemetry and self-updaters
  while keeping its core function. Generated by app-debloat from a manifest; edit the manifest, not this file.

.DESCRIPTION
  Dry run by default: resolves the install, prints the exact plan and changes nothing.
  -Apply executes exactly the printed plan (elevated PowerShell). Idempotent: a second run plans nothing.
  Every change is journaled with the state it replaced (first run wins) under
  %ProgramData%\AppDebloat\fabrikam-drive\journal.jsonl, and -Uninstall replays that journal in reverse.
  Exit code: 0 ok, 1 a step failed, 2 refused (not elevated, not installed, unsupported version, bad manifest).

.PARAMETER Apply
  Execute the plan. Needs an elevated PowerShell.

.PARAMETER Install
  Apply now and keep it applied: copies this file and the chosen options to %ProgramData%\AppDebloat\fabrikam-drive
  (admin-only) and registers the task FabrikamDriveDebloat-Watch (at logon and every 6 hours), which re-confirms
  only the blocking actions. Install only after the core-function checks passed.

.PARAMETER Uninstall
  Undo everything in the journal in reverse order, remove the tasks and the state folder.
  Files removed from the vendor install come back only by reinstalling the app; the list is printed.

.PARAMETER Auto
  Used by the FabrikamDriveDebloat-Watch task: saved options, blocking actions only, log to auto.log and history.log.

.PARAMETER InstallRoot
  Use this folder as the install root instead of resolving it.

.PARAMETER Force
  Apply even when the installed version is outside the manifest's supported range.

.PARAMETER KeepAi
  Keep the AI assistant plugin.
.PARAMETER BlockHosts
  Also sink ad and telemetry hosts in the hosts file (discouraged: flagged by security products).

.EXAMPLE
  .\FabrikamDriveDebloat.ps1              # dry run
  .\FabrikamDriveDebloat.ps1 -Apply       # do it once
  .\FabrikamDriveDebloat.ps1 -Install     # do it and keep it done after updates and repairs
  .\FabrikamDriveDebloat.ps1 -Uninstall
#>
